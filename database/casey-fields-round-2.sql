-- The INSERT is idempotent for the same event/rider/stint/lap label.

CREATE TABLE IF NOT EXISTS public.lap_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event text NOT NULL,
  rider_name text NOT NULL,
  stint integer NOT NULL DEFAULT 1,
  lap_number_as_shown text NOT NULL,
  lap_number integer,
  lap_time_as_shown text NOT NULL DEFAULT '',
  incident text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT lap_records_event_rider_stint_lap_unique UNIQUE (event, rider_name, stint, lap_number_as_shown)
);

ALTER TABLE public.lap_records ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Approved members can read lap records" ON public.lap_records;
CREATE POLICY "Approved members can read lap records"
ON public.lap_records FOR SELECT TO authenticated
USING (EXISTS (
  SELECT 1 FROM public.profiles p
  WHERE p.id = auth.uid() AND p.status = 'approved'
));

DROP POLICY IF EXISTS "Captains can manage lap records" ON public.lap_records;
CREATE POLICY "Captains can manage lap records"
ON public.lap_records FOR ALL TO authenticated
USING (EXISTS (
  SELECT 1 FROM public.profiles p
  WHERE p.id = auth.uid() AND p.status = 'approved' AND p.role = 'captain'
))
WITH CHECK (EXISTS (
  SELECT 1 FROM public.profiles p
  WHERE p.id = auth.uid() AND p.status = 'approved' AND p.role = 'captain'
));

