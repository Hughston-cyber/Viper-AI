-- VIPER AI Race Day Command Centre and private rider availability
-- Schema has been applied to the connected Supabase project.
create table if not exists public.race_day_checklist (
 id bigint generated by default as identity primary key,
 race_day_id bigint not null references public.race_days(id) on delete cascade,
 item text not null check(length(trim(item))>0), is_done boolean not null default false,
 notes text, created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists race_day_checklist_day_idx on public.race_day_checklist(race_day_id,created_at);
alter table public.race_day_checklist enable row level security;
create table if not exists public.race_day_updates (
 id bigint generated by default as identity primary key,
 race_day_id bigint not null references public.race_days(id) on delete cascade,
 message text not null check(length(trim(message))>0),
 category text not null default 'Update' check(category in ('Update','Schedule','Safety','Result')),
 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now()
);
create index if not exists race_day_updates_day_idx on public.race_day_updates(race_day_id,created_at desc);
alter table public.race_day_updates enable row level security;
create table if not exists public.rider_availability (
 id bigint generated by default as identity primary key, rider_name text not null unique check(length(trim(rider_name))>0),
 availability text not null default 'unknown' check(availability in ('available','limited','unavailable','unknown')),
 injury_status text not null default 'not_reported' check(injury_status in ('not_reported','fit','restricted','unavailable','recovering')),
 event_id bigint references public.race_days(id) on delete set null, expected_return date, private_notes text,
 updated_by uuid references auth.users(id) on delete set null, updated_at timestamptz not null default now()
);
create index if not exists rider_availability_event_idx on public.rider_availability(event_id);
alter table public.rider_availability enable row level security;
